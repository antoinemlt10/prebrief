"""End-to-end, against a seeded cache.

The fixtures below are SYNTHETIC. The organizations, dollar amounts and URLs are
invented, and none of them should ever be mistaken for a real record — that is
why they use example.gov and a made-up agency. The point of this test is the
machinery: sources → gates → assembly → render → disk, with the invariants
holding all the way through.

Real briefs are generated by `prebrief run` against the live public APIs. They
are not manufactured here, because a tool whose whole argument is provenance
cannot ship fabricated sources as if they were findings.
"""

